#!/usr/bin/env python3
"""Makes resources/legal.r (the Legal screen's text, 'TEXT' 128) from
docs/legal/legal-statement.md (Stage 9b, decision T6): plain text in
Mac Roman, headings on their own lines, bold and rules removed,
paragraphs separated by one empty line. Run it after editing the
statement, and commit both files."""

import os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
source = os.path.join(root, "docs", "legal", "legal-statement.md")
target = os.path.join(root, "resources", "legal.r")

paragraphs = []
for line in open(source, encoding="utf-8").read().splitlines():
    line = line.strip()
    if not line or line == "---":
        continue
    line = re.sub(r"^#+\s*", "", line)      # headings
    line = line.replace("**", "")           # bold
    paragraphs.append(line)

text = "\r\r".join(paragraphs) + "\r"
data = text.encode("mac_roman")

with open(target, "w") as out:
    out.write("/* The Legal screen's text (Stage 9b). Generated by "
              "tools/make-legal-r.py\n   from docs/legal/legal-statement.md: "
              "edit that, then run the tool. */\n\n")
    out.write("data 'TEXT' (128, \"Legal\") {\n")
    for i in range(0, len(data), 32):
        out.write('    $"%s"\n' % data[i:i + 32].hex().upper())
    out.write("};\n")
print("wrote", target, len(data), "bytes")
